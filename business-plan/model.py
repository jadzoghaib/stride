def eur(x: float, dp: int = 0) -> str:
    if abs(x) >= 1_000_000:
        return f"€{x/1_000_000:,.2f}M"
    if abs(x) >= 1_000:
        return f"€{x/1_000:,.0f}k"
    return f"€{x:,.{dp}f}"


def num(x: float) -> str:
    return f"{x:,.0f}"


def table(head: list[str], rows: list[list[str]]) -> str:
    out = ["| " + " | ".join(head) + " |",
           "|" + "|".join("---" for _ in head) + "|"]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(out)


def render(rows: list[dict]) -> dict[str, str]:
    ys = [f"Y{r['year']}" for r in rows]

    def line(label, key, fmt=eur):
        return [label] + [fmt(r[key]) for r in rows]

    drivers = table(["Driver"] + ys, [
        line("Active athletes", "athletes", num),
        line("Paying fans", "paying_fans", num),
        line("Sponsorship deals", "deals", num),
        line("Paying sponsors (SaaS)", "paying_sponsors", num),
        line("Headcount (FTE)", "headcount", lambda v: f"{v:,.1f}"),
    ])

    gmv = table(["Marketplace volume"] + ys, [
        line("Fan GMV (subs + unlocks)", "fan_gmv"),
        line("Sponsorship GMV", "sponsorship_gmv"),
        line("**Total GMV**", "gmv"),
    ])

    revenue = table(["Net revenue"] + ys, [
        line(f"Fan take ({A.take_fan:.0%})", "rev_fan"),
        line(f"Sponsorship take ({A.take_sponsorship:.0%})", "rev_sponsorship"),
        line("Sponsor SaaS", "rev_saas"),
        line("**Total net revenue**", "revenue"),
    ])

    pl = table(["P&L"] + ys, [
        line("Net revenue", "revenue"),
        line("Payment processing", "psp"),
        line("Payouts", "payouts"),
        line("Infrastructure (AWS)", "infra"),
        line("Moderation", "moderation"),
        line("Athlete verification", "verification"),
        line("**Gross profit**", "gross"),
        ["Gross margin"] + [f"{(r['gross']/r['revenue']*100 if r['revenue'] else 0):,.0f}%" for r in rows],
        line("People", "people"),
        line("Marketing / CAC", "marketing"),
        line("Legal & compliance", "legal"),
        line("Other opex", "other"),
        line("**EBITDA**", "ebitda"),
        line("Tax", "tax"),
        line("**Free cash flow**", "fcf"),
    ])

    egress = table(["Egress strategy"] + ys, [
        line("AWS w/ zero-egress CDN", "infra"),
        line("AWS w/ CloudFront list price", "infra_naive"),
        ["**Annual difference**"] + [eur(r["infra_naive"] - r["infra"]) for r in rows],
    ])

    v = valuation(rows)
    val = table(["Valuation (DCF)", "Value"], [
        ["PV of explicit FCF, Y1–Y7", eur(v["pv_explicit"])],
        [f"Terminal value (g={A.terminal_growth:.0%})", eur(v["terminal_value"])],
        ["PV of terminal value", eur(v["pv_terminal"])],
        [f"**Enterprise value (WACC {A.wacc:.0%})**", f"**{eur(v['enterprise_value'])}**"],
    ])

    last = rows[-1]
    df = (1 + A.wacc) ** last["year"]   # discount Y7 money back to today
    mult = table(["Exit method (Y7)", "Multiple", "Value AT Y7", "Discounted to today"], [
        ["Marketplace comparables", "4.0x revenue", eur(last["revenue"] * 4), eur(last["revenue"] * 4 / df)],
        ["Blended marketplace + SaaS", "6.5x revenue", eur(last["revenue"] * 6.5), eur(last["revenue"] * 6.5 / df)],
        ["High-growth SaaS mix", "9.0x revenue", eur(last["revenue"] * 9), eur(last["revenue"] * 9 / df)],
        ["EBITDA multiple", "14x EBITDA", eur(max(last["ebitda"], 0) * 14), eur(max(last["ebitda"], 0) * 14 / df)],
    ])

    # cumulative funding need = deepest point of cumulative FCF
    cum, trough, trough_year = 0.0, 0.0, 1
    cash_rows = []
    for r in rows:
        cum += r["fcf"]
        if cum < trough:
            trough, trough_year = cum, r["year"]
        cash_rows.append([f"Y{r['year']}", eur(r["fcf"]), eur(cum)])
    cash = table(["Year", "Free cash flow", "Cumulative"], cash_rows)

    funding = table(["Capital requirement", "Value"], [
        ["Deepest cumulative cash position", eur(trough)],
        ["Year it occurs", f"Y{trough_year}"],
        ["Buffer at 40% (hiring slips, churn worse)", eur(abs(trough) * 0.4)],
        ["**Total capital to fund the plan**", f"**{eur(abs(trough) * 1.4)}**"],
        ["First EBITDA-positive year", f"Y{next((r['year'] for r in rows if r['ebitda'] > 0), 0)}"],
    ])

    churn = table(["Retention & acquisition"] + ys, [
        line("Paying fans, year end", "paying_fans", num),
        line("Paying fans, average", "avg_fans", num),
        line("Fans acquired (gross)", "fan_gross_adds", num),
        line("Fans lost to churn", "fans_churned", num),
        line("Athletes acquired (gross)", "athlete_gross_adds", num),
        line("Athletes lost to churn", "athletes_lost", num),
    ])

    seg_rows = []
    for key, label in (("niche", "Niche (market creation)"), ("popular", "Popular (disintermediation)")):
        seg_rows.append([f"**{label}**"] + ["" for _ in rows])
        seg_rows.append(["  Athletes"] + [num(r["segs"][key]["athletes"]) for r in rows])
        seg_rows.append(["  Paying fans"] + [num(r["segs"][key]["paying_fans"]) for r in rows])
        seg_rows.append(["  Deals"] + [num(r["segs"][key]["deals"]) for r in rows])
        seg_rows.append(["  Net revenue"] + [eur(r["segs"][key]["revenue"]) for r in rows])
    seg_rows.append(["**Niche share of athletes**"] + [f"{r['niche_share']:.0%}" for r in rows])
    seg_rows.append(["**Niche share of revenue**"] + [
        f"{r['segs']['niche']['revenue'] / (r['segs']['niche']['revenue'] + r['segs']['popular']['revenue']):.0%}"
        for r in rows])
    segments = table(["Segment"] + ys, seg_rows)

    return dict(drivers=drivers, gmv=gmv, revenue=revenue, pl=pl, egress=egress,
                valuation=val, multiples=mult, cash=cash, funding=funding,
                segments=segments, churn=churn)


def unit_economics() -> str:
    """The fixed-fee problem, per transaction size."""
    rows = []
    for price in (4.99, 9.99, 14.99, 24.99, 99.00):
        take = price * A.take_fan
        psp = price * A.psp_pct + A.psp_fixed_eur
        net = take - psp
        rows.append([
            f"€{price:,.2f}",
            f"€{take:,.2f}",
            f"€{psp:,.2f}",
            f"€{net:,.2f}",
            f"{(net/take*100 if take else 0):,.0f}%",
        ])
    return table(
        ["Fan pays (monthly)", f"Our take ({A.take_fan:.0%})", "Payment cost", "We keep", "% of take retained"],
        rows,
    )


