"""Stride — 10-year financial model.

Every table in 03-financial-model.md and 04-capital-and-valuation.md is
generated by this script. Nothing in those documents is hand-typed, so the
arithmetic is reproducible and an examiner can change one assumption and see
the whole model move:

    python business-plan/model.py            # print all tables
    python business-plan/model.py --write    # regenerate the markdown docs

Currency is EUR throughout (the company is Spanish). Note the product currently
stores money in `*_usd` columns — see 05-product-gaps.md.
"""

from __future__ import annotations

