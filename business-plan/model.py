from dataclasses import dataclass, field

YEARS = list(range(1, 11))  # Y1 = 2027 .. Y10 = 2036

# Ten years, not seven. At Y7 the company is still compounding above 50%, so a
# perpetuity-growth terminal value placed there does most of the valuation work
# and does it badly. Extending to Y10 lets growth decelerate inside the explicit
# forecast, which is where it belongs.


