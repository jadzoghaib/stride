    athletes: list[int] = field(default_factory=lambda: [400, 1_800, 5_500, 13_000, 25_000, 38_000, 52_000, 65_000, 76_000, 85_000])
    # Niche first (no incumbent, acute need), popular entering from Y3 once the
    # niche cohort's earnings make the disintermediation pitch quantified.
    niche_share: list[float] = field(default_factory=lambda: [0.95, 0.92, 0.80, 0.68, 0.58, 0.50, 0.45, 0.43, 0.42, 0.41])
    segments: list[Segment] = field(default_factory=lambda: [NICHE, POPULAR])

    # one-off fan spend (unlocks + tips) as a multiple of subscription GMV
    ppv_tips_multiple: float = 0.35

    # ---- sponsor SaaS ------------------------------------------------------
    sponsors: list[int] = field(default_factory=lambda: [25, 110, 340, 800, 1_500, 2_400, 3_500, 4_600, 5_600, 6_400])
    sponsor_paid_rate: list[float] = field(default_factory=lambda: [0.10, 0.14, 0.17, 0.19, 0.20, 0.20, 0.20, 0.20, 0.20, 0.20])
    sponsor_arpu_month: list[int] = field(default_factory=lambda: [199, 229, 260, 290, 320, 360, 400, 430, 455, 475])
    # A matching product is worth nothing without athletes to match. Below this
    # pool size, paid conversion scales down with supply — otherwise the model
    # books SaaS revenue against an empty directory.
    athletes_for_full_saas_value: int = 2_000

    # ---- take rates --------------------------------------------------------
    take_fan: float = 0.15        # vs OnlyFans 20% — deliberately athlete-friendly
    take_sponsorship: float = 0.10

    # ---- payment rails (charged on GMV, not on our net revenue) ------------
    # Blended card rate for a SPANISH entity, not the US headline. Stripe EEA
    # domestic is 1.5% + EUR 0.25; UK cards 2.5%; non-EEA 3.25%. Assuming a
    # mostly-European fan base with some international tail, 1.9% is the blend.
    # An earlier version of this model used the US 2.9% and overstated the
    # largest cost line in the business by roughly a third.
    psp_pct: float = 0.019
    psp_fixed_eur: float = 0.25
    payout_pct: float = 0.0025
    payout_fixed_eur: float = 0.25
    avg_fan_txn_eur: float = 9.20   # drives how badly the fixed fee bites
    avg_deal_txn_eur: float = 1_800

    # ---- infrastructure (AWS) ---------------------------------------------
    aws_base_month: list[int] = field(default_factory=lambda: [180, 650, 2_100, 5_400, 11_000, 17_000, 24_000, 30_000, 35_000, 39_000])
    # media egress is the cost that separates a content platform from an
    # analytics one. GB per paying fan per month.
    gb_per_fan_month: float = 1.8
    egress_eur_per_gb: float = 0.008   # object storage w/ zero-egress CDN (see 02)
    egress_eur_per_gb_naive: float = 0.075  # CloudFront list — the trap

    # ---- other cost of sales ----------------------------------------------
    moderation_eur_per_1k_items: float = 22.0
    items_per_athlete_month: float = 12.0

    # ---- admission (the gate — business-plan/11-admission-and-matching.md) --
    # Applicants are not athletes. The gate admits a share of them and sends a
    # share to a human, and neither cost existed before admission was built.
    # Note what is NOT changed here: segment `cac_eur` stays as it is, because
    # it was always defined as the cost of landing one athlete ON the platform
    # (see research_data.py). Multiplying it by the funnel would double-count
    # the same money. What is genuinely new is the review labour, which is paid
    # per APPLICATION rather than per athlete.
    #
    # The direct rates are not hand-set: they are the ops-load output of
